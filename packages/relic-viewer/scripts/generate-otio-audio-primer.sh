#!/usr/bin/env bash
# Generates the silent audio primer for the rendered-program viewer, with ffmpeg only.
#
#   bash generate-otio-audio-primer.sh OUT_MP4 [MODULE_TS]
#
# OUT_MP4 receives a 4 s, 16x16 H.264 baseline video track plus an AAC-LC stereo 48 kHz audio
# track. Every audio sample is exact digital silence, and the file carries no metadata: no
# encoder tag, creation time, or track title. The muxer's generic handler names and the libx264 SEI
# build string remain; they are encoder boilerplate, not media content. Run it twice with the same
# ffmpeg build and the output is byte-identical.
#
# If MODULE_TS is given, it is also written as the generated TypeScript module the viewer imports.
# The module exports the MIME type, the byte length, the SHA-256 and the bytes as base64. Regenerate
# with this script; never edit the module by hand.
set -euo pipefail

out_mp4="${1:?usage: generate-otio-audio-primer.sh OUT_MP4 [MODULE_TS]}"
module_ts="${2:-}"

sha256_of() {
  if command -v sha256sum >/dev/null 2>&1; then
    sha256sum "$1" | awk '{print $1}'
  else
    shasum -a 256 "$1" | awk '{print $1}'
  fi
}

work="$(mktemp -d "${TMPDIR:-/tmp}/otio-audio-primer.XXXXXX")"
trap 'rm -rf "$work"' EXIT
tmp_mp4="$work/primer.mp4"

ffmpeg -hide_banner -loglevel error -y \
  -f lavfi -i "color=c=black:s=16x16:r=1" \
  -f lavfi -i "anullsrc=channel_layout=stereo:sample_rate=48000" \
  -map 0:v:0 -map 1:a:0 -t 4 \
  -c:v libx264 -profile:v baseline -pix_fmt yuv420p -g 4 -bf 0 -preset medium \
  -c:a aac -profile:a aac_low -ac 2 -ar 48000 \
  -map_metadata -1 -metadata:s:v encoder= -metadata:s:a encoder= -fflags +bitexact -flags:v +bitexact -flags:a +bitexact \
  -movflags +faststart \
  "$tmp_mp4"

# Silence is checked on decoded PCM, not on headers: any nonzero byte fails the build.
nonzero="$(ffmpeg -hide_banner -loglevel error -i "$tmp_mp4" -map 0:a:0 -f s16le -acodec pcm_s16le - \
  | tr -d '\000' | wc -c | tr -d ' ')"
if [ "$nonzero" != "0" ]; then
  echo "primer audio is not digital silence: $nonzero nonzero bytes" >&2
  exit 1
fi

mv "$tmp_mp4" "$out_mp4"
sha="$(sha256_of "$out_mp4")"
bytes="$(wc -c < "$out_mp4" | tr -d ' ')"
echo "wrote $out_mp4 ($bytes bytes, sha256 $sha)"

if [ -n "$module_ts" ]; then
  chunks="$work/base64-chunks.txt"
  base64 < "$out_mp4" | tr -d '\n' | fold -w 96 | sed 's/.*/  "&" +/' > "$chunks"
  {
    echo "// Generated by packages/relic-viewer/scripts/generate-otio-audio-primer.sh. Do not edit."
    echo "// 4 s silent 16x16 H.264 baseline and AAC-LC stereo 48 kHz primer, exact digital silence."
    echo ""
    echo "export const OTIO_AUDIO_PRIMER_MIME = \"video/mp4\";"
    echo "export const OTIO_AUDIO_PRIMER_SHA256 = \"$sha\";"
    echo "export const OTIO_AUDIO_PRIMER_BYTE_LENGTH = $bytes;"
    echo ""
    echo "const base64Text ="
    cat "$chunks"
    echo
    echo "  \"\";"
    echo ""
    echo "/** The primer MP4 bytes. A fresh copy on every call, so callers may keep or transfer it. */"
    echo "export function otioAudioPrimerBytes(): Uint8Array {"
    echo "  const binary = atob(base64Text);"
    echo "  const bytes = new Uint8Array(binary.length);"
    echo "  for (let i = 0; i < binary.length; i += 1) bytes[i] = binary.charCodeAt(i);"
    echo "  return bytes;"
    echo "}"
    echo ""
    echo "/** A Blob of the primer MP4, typed for use as a media element source. */"
    echo "export function otioAudioPrimerBlob(): Blob {"
    echo "  return new Blob([otioAudioPrimerBytes()], { type: OTIO_AUDIO_PRIMER_MIME });"
    echo "}"
  } > "$module_ts"
  echo "wrote $module_ts"
fi
